# Symbol index


def _is_test_path(rel: str) -> bool:
    parts = rel.split("/")
    return any(p.lower() in _TEST_DIRS for p in parts[:-1]) or bool(_TEST_NAME_RE.search(parts[-1]))


def _symbols_of(rel: str, text: str) -> Optional[List[Dict[str, Any]]]:
    """Anchorable symbols of one code file (None: the file does not parse, so no anchor into it could be active)."""
    out: List[Dict[str, Any]] = []
    suffix = Path(rel).suffix.lower()
    if suffix == ".py":
        try:
            tree = ast.parse(text)
            nodes = _collect_scoped_ast_nodes(tree.body)
        except (SyntaxError, ValueError, RecursionError, MemoryError):
            return None
        for qname, name, nested, node in nodes:
            if "<locals>" in qname or not _SYMBOL_RE.fullmatch(qname):
                continue
            kind = "class" if isinstance(node, ast.ClassDef) else ("method" if nested else "function")
            out.append({"symbol": qname, "name": name, "line": int(getattr(node, "lineno", 0) or 0), "kind": kind})
        return out
    if suffix in _TS_JS_EXTS:
        try:
            ok, sigs = _extract_ts_js_signatures(text)
        except (RecursionError, MemoryError, ValueError):
            return None
        if not ok:
            return None
        dotted_ids = {id(s) for k, s in sigs.items() if "." in k}
        for key in sorted(sigs):
            sig = sigs[key]
            if key == "default" or not isinstance(sig, dict) or sig.get("kind") == "ambiguous_method":
                continue
            if "." not in key and id(sig) in dotted_ids:
                continue  # the short alias of `Class.method`: indexed through the qualified entry
            if not _SYMBOL_RE.fullmatch(key):
                continue
            kind = "method" if "." in key else str(sig.get("kind") or "symbol")
            out.append({"symbol": key, "name": key.rsplit(".", 1)[-1], "line": int(sig.get("line") or 0), "kind": kind})
        return out
    return []


def _read_code(root: Path, rel: str) -> Optional[str]:
    if mw.contained_path_problem(root, rel) or mw._is_secret_path(rel):
        return None
    return mw.read_regular_text(root / rel, MAX_INDEX_FILE_BYTES)


class SymbolIndex:
    """Anchorable symbols of the repository, keyed by their last name component. Built once per command."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.by_name: Dict[str, List[Dict[str, Any]]] = {}
        self.files: Dict[str, Optional[List[Dict[str, Any]]]] = {}
        self.basenames: Dict[str, List[str]] = {}
        self.truncated: List[str] = []
        self.stats = {"codeFiles": 0, "symbols": 0, "bytes": 0, "generatedSkipped": 0, "oversizedSkipped": 0,
                      "parseErrors": 0, "walkEntries": 0}
        self._build()

    def _add_file(self, rel: str, text: str) -> None:
        syms = _symbols_of(rel, text)
        self.files[rel] = syms
        self.basenames.setdefault(rel.rsplit("/", 1)[-1], []).append(rel)
        if syms is None:
            self.stats["parseErrors"] += 1
            return
        test = _is_test_path(rel)
        for s in syms:
            entry = dict(s, path=rel, anchor=f"{rel}::{s['symbol']}", test=test)
            self.by_name.setdefault(s["name"], []).append(entry)
            self.stats["symbols"] += 1

    def _build(self) -> None:
        root = self.root
        seen = 0
        for cur, dirs, files in os.walk(root):
            rel_dir = Path(cur).relative_to(root).as_posix()
            rel_dir = "" if rel_dir == "." else rel_dir
            if rel_dir and (Path(cur) / ".git").exists():
                dirs[:] = []
                continue  # a nested repository / worktree: its code belongs to that repository
            dirs[:] = sorted(d for d in dirs if d not in _SKIP_DIRS and not d.startswith(".")
                             and not os.path.islink(os.path.join(cur, d)))
            seen += len(dirs) + len(files)
            self.stats["walkEntries"] = seen
            if seen > MAX_WALK_ENTRIES:
                self.truncated.append(f"walk_entries>{MAX_WALK_ENTRIES}")
                return
            for fn in sorted(files):
                if Path(fn).suffix.lower() not in _INDEX_EXTS:
                    continue
                rel = f"{rel_dir}/{fn}" if rel_dir else fn
                if _GENERATED_NAME_RE.search(fn):
                    self.stats["generatedSkipped"] += 1
                    continue
                try:
                    st = os.lstat(os.path.join(cur, fn))
                except OSError:
                    continue
                if not os.path.isfile(os.path.join(cur, fn)) or os.path.islink(os.path.join(cur, fn)):
                    continue
                if st.st_size > MAX_INDEX_FILE_BYTES:
                    self.stats["oversizedSkipped"] += 1
                    continue
                if self.stats["codeFiles"] >= MAX_INDEX_FILES:
                    self.truncated.append(f"code_files>{MAX_INDEX_FILES}")
                    return
                if self.stats["bytes"] + st.st_size > MAX_INDEX_TOTAL_BYTES:
                    self.truncated.append(f"code_bytes>{MAX_INDEX_TOTAL_BYTES}")
                    return
                text = _read_code(root, rel)
                if text is None:
                    continue
                if _GENERATED_HEAD_RE.search(text[:2048]):
                    self.stats["generatedSkipped"] += 1
                    continue
                self.stats["codeFiles"] += 1
                self.stats["bytes"] += st.st_size
                self._add_file(rel, text)

    def file_symbols(self, rel: str) -> Optional[List[Dict[str, Any]]]:
        """Symbols of one file, parsed on demand when the walk skipped it (cap, generated name). Excluded folders
        (node_modules, .memlet, ...), symlinks and secrets are never read."""
        if rel in self.files:
            return self.files[rel]
        parts = rel.split("/")
        if (Path(rel).suffix.lower() not in _INDEX_EXTS or any(p in _SKIP_DIRS for p in parts[:-1])
                or mw._unsafe_rel(rel)):
            return None
        text = _read_code(self.root, rel)
        if text is None:
            self.files[rel] = None
            return None
        syms = _symbols_of(rel, text)
        self.files[rel] = syms
        return syms

    def resolve_file(self, source: str, path: str) -> Optional[str]:
        """A mentioned path as a repository file: root-relative, relative to the rule's own file, or the one indexed
        file with that path suffix. None when it is not a code file Memlet indexes or the suffix is ambiguous."""
        path = mw._clean_ref_path(path)
        if mw._unsafe_rel(path) or Path(path).suffix.lower() not in _INDEX_EXTS:
            return None
        parent = Path(source).parent.as_posix()
        for cand in ([path] + ([f"{parent}/{path}"] if parent not in ("", ".") else [])):
            if cand in self.files or (not mw._unsafe_rel(cand) and (self.root / cand).is_file()
                                      and not mw.contained_path_problem(self.root, cand)):
                return cand
        tail = "/" + path
        hits = [rel for rel in self.basenames.get(path.rsplit("/", 1)[-1], []) if rel == path or rel.endswith(tail)]
        return hits[0] if len(hits) == 1 else None

    def lookup(self, name: str) -> List[Dict[str, Any]]:
        last = name.rsplit(".", 1)[-1]
        return [e for e in self.by_name.get(last, []) if e["symbol"] == name or e["symbol"].endswith("." + name)
                or "." not in name]


