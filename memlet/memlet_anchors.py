def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def suggestion_id(source: str, rule_sha: str, anchor: str) -> str:
    """Stable id of a suggestion / sidecar entry: the same rule text, source and anchor always give the same id."""
    return "anc-" + _sha256(f"{source}\n{rule_sha}\n{anchor}")[:12]


def _mask(text: str) -> str:
    from .memlet_brief import _mask as mask
    return mask(text)


def _clip(text: str, limit: int = _RULE_DISPLAY) -> str:
    text = re.sub(r"\s+", " ", text or "").strip()
    return text if len(text) <= limit else text[:limit - 1] + "…"


