def _resolve(index: SymbolIndex, rule: Dict[str, Any]) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]], int]:
    """(suggestions, ambiguous, unresolved count) for one rule. Precision first: a `file+symbol` needs the symbol in
    a file the same rule names; a `unique-symbol` needs a distinctive name defined exactly once in a complete index."""
    mentions = rule_mentions(rule["fullText"])
    files = []
    for path, sym in mentions["files"]:
        rel = index.resolve_file(rule["source"], path)
        if rel and rel not in files:
            files.append(rel)
    sugg, amb, unresolved = [], [], 0
    for name, call in mentions["idents"]:
        in_files = []
        for rel in files:
            for s in index.file_symbols(rel) or []:
                if s["symbol"] == name or s["symbol"].endswith("." + name):
                    in_files.append(dict(s, path=rel, anchor=f"{rel}::{s['symbol']}", test=_is_test_path(rel)))
        if len(in_files) == 1:
            t = in_files[0]
            sugg.append(_suggestion(rule, t, "file+symbol", name,
                                    f"the rule names `{t['path']}` and `{name}`, defined there at line {t['line']} ({t['kind']})"))
            continue
        if len(in_files) > 1:
            amb.append(_ambiguous(rule, name, "several_matches_in_named_file", in_files))
            continue
        cands = sorted(index.lookup(name), key=lambda e: (e["path"], e["line"], e["symbol"]))
        if not cands:
            unresolved += 1
            continue
        if len(cands) > 1:
            reason = "defined_in_tests_and_source" if any(c["test"] for c in cands) and not all(c["test"] for c in cands) \
                else "multiple_definitions"
            amb.append(_ambiguous(rule, name, reason, cands))
            continue
        if not _distinctive(name, call):
            amb.append(_ambiguous(rule, name, "name_too_generic_to_anchor_without_a_file", cands))
            continue
        if index.truncated:
            amb.append(_ambiguous(rule, name, "symbol_index_truncated_uniqueness_unproven", cands))
            continue
        t = cands[0]
        sugg.append(_suggestion(rule, t, "unique-symbol", name,
                                f"`{name}` is defined exactly once in the indexed repository: {t['path']}:{t['line']} ({t['kind']})"
                                + ("; that definition is in a test file" if t["test"] else "")))
    return sugg, amb, unresolved


def _suggestion(rule, target, confidence, mention, reason) -> Dict[str, Any]:
    anchor = f"{target['path']}::{target['symbol']}"
    return {"id": suggestion_id(rule["source"], rule["ruleSha256"], anchor), "source": rule["source"],
            "line": rule["line"], "ruleSha256": rule["ruleSha256"], "rule": _clip(_mask(rule["fullText"])),
            "anchor": anchor, "confidence": confidence, "reason": reason, "mention": mention,
            "target": {"path": target["path"], "symbol": target["symbol"], "line": target["line"],
                       "kind": target["kind"], "test": bool(target.get("test"))}}


def _ambiguous(rule, mention, reason, cands) -> Dict[str, Any]:
    return {"source": rule["source"], "line": rule["line"], "ruleSha256": rule["ruleSha256"],
            "rule": _clip(_mask(rule["fullText"])), "mention": mention, "reason": reason, "candidateCount": len(cands),
            "candidates": [{"anchor": c["anchor"], "line": c["line"], "kind": c["kind"], "test": bool(c.get("test"))}
                           for c in cands[:MAX_CANDIDATES_SHOWN]]}


def _suggest(root: Path, limit: Optional[int]) -> Dict[str, Any]:
    sources = rule_sources(root)
    accepted = {(e["source"], e["ruleSha256"], e["anchor"]) for e in sidecar_anchors(root)}
    rules: List[Dict[str, Any]] = []
    rules_truncated = False
    for rel, text in sources:
        for r in _rules_of(rel, text):
            if len(rules) >= MAX_RULES:
                rules_truncated = True
                break
            rules.append(r)
    index = SymbolIndex(root)
    sugg: List[Dict[str, Any]] = []
    amb: List[Dict[str, Any]] = []
    unresolved = already = written = 0
    dup = {}
    for r in rules:
        dup[(r["source"], r["ruleSha256"])] = dup.get((r["source"], r["ruleSha256"]), 0) + 1
    for r in rules:
        if _written_anchor(r):
            written += 1
            continue
        s, a, u = _resolve(index, r)
        unresolved += u
        if s and dup[(r["source"], r["ruleSha256"])] > 1:
            amb.append(dict(_ambiguous(r, s[0]["mention"], "rule_text_repeated_in_file", []),
                            candidates=[{"anchor": x["anchor"], "line": x["target"]["line"], "kind": x["target"]["kind"],
                                         "test": x["target"]["test"]} for x in s]))
            s = []
        seen = set()
        for x in s:
            if x["anchor"] in seen:
                continue
            seen.add(x["anchor"])
            if (x["source"], x["ruleSha256"], x["anchor"]) in accepted:
                already += 1
                continue
            sugg.append(x)
        amb.extend(a)
    sugg.sort(key=lambda x: (x["source"], x["line"], x["anchor"]))
    amb.sort(key=lambda x: (x["source"], x["line"], x["mention"]))
    truncated = bool(index.truncated) or rules_truncated
    if limit is not None and (len(sugg) > limit or len(amb) > limit):
        truncated = True
    shown_s = sugg if limit is None else sugg[:limit]
    shown_a = amb if limit is None else amb[:limit]
    scanned = dict(index.stats, rules=len(rules), rulesWithWrittenAnchors=written,
                   sources=len(sources), unresolvedMentions=unresolved)
    return {"ok": True, "exitCode": 0, "command": "anchors suggest", "repoPath": str(root),
            "suggestions": shown_s, "ambiguous": shown_a, "suggestionCount": len(sugg), "ambiguousCount": len(amb),
            "alreadyAccepted": already, "scanned": scanned, "truncated": truncated,
            "truncation": list(index.truncated) + ([f"rules>{MAX_RULES}"] if rules_truncated else [])
            + (["limit"] if limit is not None and (len(sugg) > limit or len(amb) > limit) else [])}


def suggest_anchors(repo_path=".", *, limit=200) -> Dict[str, Any]:
    """Suggested `path::symbol` anchors for rules that mention code without writing an anchor. Read-only, no model
    call. {ok, suggestions:[{id, source, line, ruleSha256, rule, anchor, confidence, reason, mention, target}],
    ambiguous:[{source, line, ruleSha256, rule, mention, reason, candidates}], scanned, truncated, ...}."""
    root = mw._resolve_root(repo_path)
    res = _suggest(root, max(0, int(limit)) if limit is not None else None)
    res["formatted"] = format_suggestions(res)
    return res


def count_suggestions(root: Path) -> int:
    """How many rules could be anchored now (for `memlet init`'s one-line hint)."""
    return len({(s["source"], s["line"]) for s in _suggest(root, None)["suggestions"]})


def format_suggestions(res: Dict[str, Any]) -> str:
    sc = res.get("scanned") or {}
    lines = ["## Memlet anchor suggestions", "",
             f"- Scanned {sc.get('rules', 0)} rule(s) in {sc.get('sources', 0)} file(s); {sc.get('codeFiles', 0)} code "
             f"file(s), {sc.get('symbols', 0)} symbol(s){' (TRUNCATED: ' + ', '.join(res.get('truncation') or []) + ')' if res.get('truncated') else ''}",
             f"- {res.get('suggestionCount', 0)} suggestion(s) · {res.get('ambiguousCount', 0)} ambiguous (not suggested)"
             f" · {res.get('alreadyAccepted', 0)} already accepted",
             "- Nothing is changed by this command. `memlet admin anchors accept ID…` (or `--all-unique`) stores the "
             "anchor in `.memlet/config.json`; your files are never edited. Check that the rule really means that code."]
    if res.get("suggestions"):
        lines += ["", "### Suggestions", ""]
        for s in res["suggestions"]:
            t = s["target"]
            lines.append(f"- `{s['id']}` ({s['confidence']}) `{s['source']}:{s['line']}`: {s['rule']}")
            lines.append(f"  → `{s['anchor']}` at `{t['path']}:{t['line']}` ({t['kind']}{', test file' if t['test'] else ''}) — {s['reason']}")
    if res.get("ambiguous"):
        lines += ["", "### Ambiguous (never guessed)", ""]
        for a in res["ambiguous"]:
            cands = ", ".join(f"`{c['anchor']}` (line {c['line']}{', test' if c['test'] else ''})" for c in a["candidates"])
            more = a.get("candidateCount", 0) - len(a["candidates"])
            lines.append(f"- `{a['source']}:{a['line']}` `{a['mention']}`: {a['reason']}"
                         + (f" — candidates: {cands}" if cands else "") + (f" (+{more} more)" if more > 0 else ""))
    return "\n".join(lines) + "\n"


