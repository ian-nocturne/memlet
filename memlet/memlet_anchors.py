# Mentions


def rule_mentions(text: str) -> Dict[str, List[Any]]:
    """Code mentions in one rule (bounded, linear): `files` [(path, symbol or None)] from backticked paths
    (`` `src/a.py` ``, `` `src/a.py#name` ``) and `idents` [(name, call_form)] from backticked identifiers
    (`` `name` ``, `` `Cls.name` ``, `` `name(x)` ``) and prose `name()` forms. Written `::` anchors are not mentions."""
    text = (text or "")[:MAX_RULE_SCAN_CHARS]
    files: List[Tuple[str, Optional[str]]] = []
    idents: List[Tuple[str, bool]] = []

    def add(lst, item):
        if item not in lst and len(files) + len(idents) < MAX_MENTIONS_PER_RULE:
            lst.append(item)

    for m in _SPAN_RE.finditer(text):
        span = m.group(1).strip()
        if not span or "::" in span:
            continue
        fm = BACKTICK_FILE_RE.fullmatch("`" + span + "`")
        if fm:
            path = mw._clean_ref_path(fm.group("path"))
            if path.lower() in IGNORED_FILE_TOKENS:
                continue
            sym = fm.group("symbol")
            add(files, (path, sym.rstrip(".-") if sym else None))
            if sym:
                add(idents, (sym.rstrip(".-"), False))
            continue
        im = _IDENT_RE.fullmatch(span)
        if im:
            add(idents, (im.group("name"), bool(im.group("call"))))
    prose = _SPAN_RE.sub(lambda m: " " * len(m.group(0)), text)
    for m in _PROSE_CALL_RE.finditer(prose):
        name = m.group("name")
        if BACKTICK_FILE_RE.fullmatch("`" + name + "`"):
            continue  # `config.py()` is a file name, not a call
        add(idents, (name, True))
    return {"files": files, "idents": idents}


def _distinctive(name: str, call_form: bool) -> bool:
    """Could this name only mean code? Dotted, snake_case, camelCase / PascalCase, or written as a call, and not a
    generic word. Used only for `unique-symbol` resolutions; a file mention makes any name precise enough."""
    last = name.rsplit(".", 1)[-1]
    if last.lower() in COMMON_NAMES or len(last) < 3:
        return False
    if "." in name or "_" in last.strip("_") or call_form:
        return True
    return bool(re.search(r"[a-z][A-Z]", last)) or (last[:1].isupper() and len(last) >= 4 and any(c.islower() for c in last))


def mentions_symbol(text: str, symbol: str) -> bool:
    """Does the rule text itself mention `symbol` (its full dotted name or a dotted tail of it)?"""
    for name, _call in rule_mentions(text)["idents"]:
        if symbol == name or symbol.endswith("." + name):
            return True
    return False


