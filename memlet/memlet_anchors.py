"""Automatic anchor suggestions and sidecar anchors (Memlet 9.1, unit D2).

Memlet can only re-check a rule that names code as `path::symbol`, and almost no instruction file is written that way.
The rules do mention code, in backticks and in prose (`validate_token()`, `` `src/auth.py` ``). This module finds those
mentions and offers the anchor itself:

* `suggest_anchors` reads the rules of the discovered instruction files and hand-written wiki pages that carry no
  `::` anchor, collects their backticked identifiers / paths and `name()` forms, and resolves them against a symbol
  index of the repository built with the existing extractors (Python AST, TS/JS lexical scanner). It suggests only
  an unambiguous resolution: a mentioned file plus a symbol defined in it (`file+symbol`), or a distinctive name
  defined exactly once in the repository (`unique-symbol`). Everything else is listed under `ambiguous` with its
  candidates, never guessed. Bounded work (file / byte / walk caps), deterministic output, no model call.
* `accept_suggestions` stores `{id, source, line, ruleSha256, anchor, pin}` in `.memlet/config.json`
  (`sidecarAnchors`) under the Memlet write lock and records each acceptance in the ledger. The user's files are never
  edited. Acceptance is a pinning event, like `init`.
* From then on (`sidecar_index` / `attach_sidecar_refs`, called by `memlet_wiki`) the rule is checked like a rule
  that had written `path::symbol` itself, in `check`, `recall`, `handover`, the hooks and MCP, with the anchor marked
  `suggested: true`. An entry is honoured only while (a) its shape is valid, (b) the ledger holds an `accept` record
  for exactly this entry (a hand-edited entry is not trusted), (c) its source still holds exactly one rule with the
  recorded SHA-256 (edited, removed or duplicated text detaches it; it is never re-attached to different text), and
  (d) that rule text still mentions the symbol (a sidecar entry cannot point an unrelated rule at a symbol).
"""

